"""Recover an empty native USD import using an isolated installed Maya reader.

No plugin is unloaded in the artist's session. Only trusted Maya ASCII generated
by the isolated local Maya process is imported; source assets are never edited.
"""

import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

WORKER_ROOT = "_USDNativeTransfer"


def recover(report, operation, mode):
    import maya.cmds as cmds
    from .core import ToolError, _created, _maya_path

    executable = Path(sys.executable).with_name("mayapy.exe" if os.name == "nt" else "mayapy")
    if not executable.is_file():
        raise ToolError(
            "当前 Maya 的原生 USD 导入只生成空层级，且找不到配套 mayapy。请保存工作并重启 Maya 后重试。"
        )
    root = operation["root"]
    root_uuid = cmds.ls(root, uuid=True)[0]
    # Remove exactly the nodes of the unsuccessful native attempt, retaining
    # our transaction root and every node that existed before the operation.
    for _, uid in reversed(_created(operation["before"])):
        if uid == root_uuid:
            continue
        paths = cmds.ls(uid, long=True) or []
        if paths:
            cmds.delete(paths[0])
    with tempfile.TemporaryDirectory(prefix="maya_usd_native_") as temporary:
        folder = Path(temporary).resolve()
        profile = folder / "maya_profile"
        profile.mkdir()
        output = folder / "native.ma"
        request = folder / "request.json"
        request.write_text(
            json.dumps(
                {
                    "source": _maya_path(report["path"]),
                    "output": output.as_posix(),
                    "meshes": report["meshes"],
                    "mode": mode,
                }
            ),
            encoding="utf-8",
        )
        environment = dict(os.environ)
        environment.pop("PYTHONHOME", None)
        environment.pop("PYTHONPATH", None)
        environment.update(
            MAYA_APP_DIR=str(profile),
            MAYA_SKIP_USERSETUP_PY="1",
            QT_QPA_PLATFORM="offscreen",
            PYTHONIOENCODING="utf-8",
        )
        try:
            process = subprocess.run(
                [str(executable), "-u", str(Path(__file__).resolve()), str(request)],
                cwd=str(folder),
                env=environment,
                stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT,
                timeout=45,
                creationflags=subprocess.CREATE_NO_WINDOW if os.name == "nt" else 0,
            )
        except (OSError, subprocess.TimeoutExpired) as error:
            raise ToolError(
                "Maya 原生 USD 没有生成网格，独立兼容读取也未完成：" + str(error)
            ) from error
        validation = folder / "result.json"
        if process.returncode or not output.is_file() or not validation.is_file():
            detail = process.stdout.decode("utf-8", errors="replace")[-1800:]
            raise ToolError(
                "Maya 原生 USD 没有生成网格，独立兼容读取失败。请保存工作并重启 Maya 后重试。\n"
                + detail
            )
        transferred = json.loads(validation.read_text(encoding="utf-8"))
        if not transferred.get("passed") or transferred.get("meshes") != report["meshes"]:
            raise ToolError("兼容读取的网格数不匹配，已停止本次导入。")
        # This file is generated by our installed Maya worker, not downloaded
        # Maya code. Import into this operation's unique namespace only.
        cmds.file(
            str(output),
            i=True,
            type="mayaAscii",
            namespace=":" + operation["namespace"],
            mergeNamespacesOnClash=True,
            ignoreVersion=True,
            returnNewNodes=True,
            options="v=0;",
        )
        cmds.namespace(setNamespace=":" + operation["namespace"])
        carrier = "|" + operation["namespace"] + ":" + WORKER_ROOT
        if not cmds.objExists(carrier):
            raise ToolError("兼容读取缺少临时根节点，已停止本次导入。")
        for child in cmds.listRelatives(carrier, children=True, fullPath=True) or []:
            cmds.parent(child, root, relative=True)
        cmds.delete(carrier)
    message = "当前会话的原生 USD 读取未生成网格，已通过独立 Maya 兼容读取恢复；工作会话插件和源 USD 未改动。"
    if report.get("instances"):
        message += "兼容传输可能把共享实例展开为独立网格；请留意大场景内存开销。"
    return message


def worker(request_path):
    """Export a complete native hierarchy in a clean Maya standalone process."""
    import maya.standalone

    maya.standalone.initialize(name="python")
    try:
        import maya.cmds as cmds

        request_path = Path(request_path)
        request = json.loads(request_path.read_text(encoding="utf-8"))
        assert request["mode"] in ("pbr", "phong_preview", "phong")
        cmds.loadPlugin("mayaUsdPlugin", quiet=True)
        cmds.currentUnit(linear="cm")
        cmds.upAxis(axis="y")
        root = cmds.createNode("transform", name=WORKER_ROOT)
        cmds.mayaUSDImport(
            file=request["source"],
            parent=root,
            primPath="/",
            readAnimData=False,
            shadingMode=(
                [("none", "")]
                if request["mode"] != "phong"
                else [("useRegistry", "UsdPreviewSurface")]
            ),
            preferredMaterial="phong",
            importInstances=True,
        )
        meshes = cmds.ls(root, dag=True, type="mesh", long=True, allPaths=True) or []
        if len(meshes) != request["meshes"]:
            raise RuntimeError(
                "Isolated Maya native reader returned {} meshes instead of {}.".format(
                    len(meshes), request["meshes"]
                )
            )
        cmds.select(root, replace=True)
        cmds.file(
            request["output"], type="mayaAscii", exportSelected=True, force=True, options="v=0;"
        )
        request_path.with_name("result.json").write_text(
            json.dumps({"passed": True, "meshes": len(meshes)}), encoding="utf-8"
        )
    finally:
        maya.standalone.uninitialize()


if __name__ == "__main__":
    worker(sys.argv[1])
